import { SPEED_OPTIONS, useSimulationStore } from '../store/useSimulationStore'
import { dayPeriod, formatClock } from '../utils/format'

/** Bottom bar: play/pause, simulated clock, time of day, playback speed and traffic density. */
export function SimulationBar() {
  const status = useSimulationStore((s) => s.status)
  const error = useSimulationStore((s) => s.error)
  const controller = useSimulationStore((s) => s.controller)
  const playing = useSimulationStore((s) => s.playing)
  const speed = useSimulationStore((s) => s.speed)
  const density = useSimulationStore((s) => s.density)
  const clock = useSimulationStore((s) => s.stats?.clock ?? 7.5 * 3600)

  if (status === 'error') {
    return (
      <div className="sim-bar panel" role="alert">
        <span className="sim-note">{error}</span>
      </div>
    )
  }

  const ready = status === 'ready' && controller

  return (
    <div className="sim-bar panel" role="group" aria-label="Traffic simulation controls">
      <button
        className="play-button"
        disabled={!ready}
        onClick={() => controller?.setPlaying(!playing)}
        aria-label={playing ? 'Pause simulation' : 'Play simulation'}
        title={`${playing ? 'Pause' : 'Play'} (Space)`}
      >
        {playing ? (
          <svg viewBox="0 0 16 16" aria-hidden="true">
            <rect x="4" y="3" width="3" height="10" rx="1" />
            <rect x="9" y="3" width="3" height="10" rx="1" />
          </svg>
        ) : (
          <svg viewBox="0 0 16 16" aria-hidden="true">
            <path d="M5 3.2v9.6a.6.6 0 0 0 .9.5l7.6-4.8a.6.6 0 0 0 0-1L5.9 2.7a.6.6 0 0 0-.9.5z" />
          </svg>
        )}
      </button>

      <div className="sim-clock">
        <span className="sim-time">{ready ? formatClock(clock) : '--:--'}</span>
        <span className="sim-period">{ready ? dayPeriod(clock) : 'Loading roads…'}</span>
      </div>

      <label className="sim-field sim-timeline">
        <span>Time of day</span>
        <input
          type="range"
          min={0}
          max={1435}
          step={5}
          value={Math.floor(clock / 60)}
          disabled={!ready}
          onChange={(e) => controller?.setClock(Number(e.target.value) * 60)}
          aria-valuetext={formatClock(clock)}
        />
      </label>

      <div className="sim-field">
        <span id="sim-speed-label">Speed</span>
        <div className="segmented" role="radiogroup" aria-labelledby="sim-speed-label">
          {SPEED_OPTIONS.map((option) => (
            <button
              key={option}
              role="radio"
              aria-checked={speed === option}
              className={speed === option ? 'active' : undefined}
              disabled={!ready}
              onClick={() => controller?.setSpeed(option)}
            >
              {option}×
            </button>
          ))}
        </div>
      </div>

      <label className="sim-field sim-density">
        <span>
          Traffic <b>{density.toLocaleString('en-GB')}</b> cars at peak
        </span>
        <input
          type="range"
          min={100}
          max={1500}
          step={50}
          value={density}
          disabled={!ready}
          onChange={(e) => controller?.setDensity(Number(e.target.value))}
        />
      </label>

      <span className="sim-badge" title="All traffic shown is generated by a model, not observed">
        Simulated
      </span>
    </div>
  )
}
